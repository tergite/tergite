import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Dict, Iterable, Set

import black
import isort
from datamodel_code_generator import DataModelType, InputFileType, generate

OPENAPI_DIR = Path(__file__).parent
ROOT_DIR = OPENAPI_DIR.parents[1]
HEADER = """# This code is part of Tergite
#
# (C) Copyright Chalmers Next Labs 2026
#
# This code is licensed under the Apache License, Version 2.0. You may
# obtain a copy of this license in the LICENSE.txt file in the root directory
# of this source tree or at http://www.apache.org/licenses/LICENSE-2.0.
#
# Any modifications or derivative works of this code must retain this
# copyright notice, and modified files need to carry a notice indicating
# that they have been altered from the originals.
#
# Generated by dev/openapi/generate.py from dev/openapi/{spec}; do not edit."""


@dataclass(frozen=True)
class Contract:
    spec_file: Path
    models_file: Path
    schemas: tuple[str, ...]


CONTRACTS = (
    Contract(
        spec_file=OPENAPI_DIR / "mss.json",
        models_file=ROOT_DIR / "tergite" / "api" / "mss_models.py",
        schemas=(
            "CreatedJobResponse",
            "Device",
            "DeviceCalibration",
            "Job",
            "JobCreate",
            "JobResult",
            "JobStatus",
            "PaginatedListResponse_Device_",
        ),
    ),
    Contract(
        spec_file=OPENAPI_DIR / "bcc.json",
        models_file=ROOT_DIR / "tergite" / "api" / "bcc_models.py",
        schemas=("CancellationDetails", "GeneralMessage", "Job", "JobFile"),
    ),
)


def main() -> None:
    for contract in CONTRACTS:
        contract.models_file.write_text(render_models(contract))


def render_models(contract: Contract) -> str:
    """Renders the Python source of the contract's models, from its spec

    Args:
        contract: the spec, the schemas the SDK reads from it, and where their models go

    Returns:
        the source of the models module
    """
    spec = json.loads(contract.spec_file.read_text())
    pruned = prune_spec(spec, contract.schemas)
    with tempfile.TemporaryDirectory() as folder:
        output = Path(folder) / "models.py"
        generate(
            json.dumps(pruned),
            input_file_type=InputFileType.OpenAPI,
            output=output,
            output_model_type=DataModelType.PydanticV2BaseModel,
            custom_file_header=HEADER.format(spec=contract.spec_file.name),
            use_standard_collections=True,
            use_union_operator=True,
            use_schema_description=True,
            use_double_quotes=True,
            collapse_root_models=True,
            use_tuple_for_fixed_items=True,
            disable_timestamp=True,
            # formatted below, as this repository's black and isort settings would format it
            formatters=[],
        )
        source = output.read_text()
    return black.format_str(isort.code(source, profile="black"), mode=black.Mode())


def prune_spec(spec: Dict[str, Any], schemas: Iterable[str]) -> Dict[str, Any]:
    """The spec without paths, and with only the schemas and those they refer to"""
    all_schemas = spec["components"]["schemas"]
    kept = _get_referred_schemas(all_schemas, set(schemas))
    return {
        "openapi": spec["openapi"],
        "info": spec["info"],
        "paths": {},
        "components": {
            "schemas": {name: _make_lenient(all_schemas[name]) for name in sorted(kept)}
        },
    }


def _make_lenient(node: Any) -> Any:
    """The schema node, and every node in it, as lenient as a client reading it should be:

    - a read-only field is optional: the services dump with exclude_none, so a null one,
      such as a job's duration_in_secs, is left out though the schema requires it;
    - a string has no pattern: the service validates its own ids, and the SDK only passes
      them back.
    """
    if isinstance(node, list):
        return [_make_lenient(item) for item in node]
    if not isinstance(node, dict):
        return node

    schema = {
        key: _make_lenient(value) for key, value in node.items() if key != "pattern"
    }
    if "required" in schema and isinstance(schema.get("properties"), dict):
        properties = schema["properties"]
        schema["required"] = [
            name
            for name in schema["required"]
            if not properties.get(name, {}).get("readOnly")
        ]
    return schema


def _get_referred_schemas(all_schemas: Dict[str, Any], names: Set[str]) -> Set[str]:
    """The schemas named, and every schema they refer to, however deep"""
    kept: Set[str] = set()
    pending = list(names)
    while pending:
        name = pending.pop()
        if name in kept:
            continue
        kept.add(name)
        pending.extend(_get_refs(all_schemas[name]))
    return kept


def _get_refs(node: Any) -> Iterable[str]:
    """The names of the schemas the node refers to"""
    if isinstance(node, dict):
        ref = node.get("$ref")
        if isinstance(ref, str) and ref.startswith("#/components/schemas/"):
            yield ref.rsplit("/", 1)[-1]
        for value in node.values():
            yield from _get_refs(value)
    elif isinstance(node, list):
        for item in node:
            yield from _get_refs(item)


if __name__ == "__main__":
    main()
