"""Generates the SDK's models of what MSS and the backend send and receive, from their specs

Run from the repository root: `python -m dev.openapi.generate`. Each spec is a copy of the
service's committed OpenAPI schema (dev/openapi/sync.sh copies them), pruned to the schemas
the SDK reads and those they refer to, so that a change elsewhere in the service does not
touch the SDK. tests/test_openapi.py fails when a generated file no longer matches its spec.
"""
